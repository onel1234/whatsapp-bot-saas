-- Local development only. Production supplies a separate strong role password.
CREATE ROLE saha_app LOGIN PASSWORD 'saha_dev_app' NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS;
GRANT CONNECT ON DATABASE saha TO saha_app;
GRANT USAGE ON SCHEMA public TO saha_app;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO saha_app;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO saha_app;
CREATE EXTENSION IF NOT EXISTS vector;
